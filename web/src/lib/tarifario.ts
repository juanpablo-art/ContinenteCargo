export interface MarketReference {
  compraMedia: number;
  ventaSugerida: number;
  ventaMinima: number;
  ventaAlta: number;
}

function normalize(value: string): string {
  return value.normalize('NFD').replace(/\p{M}/gu, '').toUpperCase().trim();
}

function detectPort(city: string): string | null {
  const name = normalize(city);
  if (name.includes('VERACRUZ')) return 'VERACRUZ';
  if (name.includes('MANZANILLO')) return 'MANZANILLO';
  if (name.includes('LAZARO')) return 'LAZARO CARDENAS';
  if (name.includes('ALTAMIRA')) return 'ALTAMIRA';
  return null;
}

function modalidad(equipmentType: string): 'SENCILLO' | 'FULL' | null {
  if (equipmentType === 'Sencillo Portacontenedor') return 'SENCILLO';
  if (equipmentType === 'Full Portacontenedor') return 'FULL';
  return null;
}

function priced(compraMedia: number): MarketReference {
  return {
    compraMedia,
    ventaSugerida: Math.round(compraMedia * 1.15),
    ventaMinima: Math.round(compraMedia * 1.13),
    ventaAlta: Math.round(compraMedia * 1.2),
  };
}

/** Market reference for a port container drayage. Null for any other equipment or origin. */
export function referencePrice(
  originCity: string,
  destinationCity: string,
  equipmentType: string,
): MarketReference | null {
  const port = detectPort(originCity);
  const modal = modalidad(equipmentType);
  if (!port || !modal) return null;
  const dest = normalize(destinationCity);
  const exact = RATES[`${port}|${dest}|${modal}`];
  if (exact != null) return priced(exact);
  const prefix = `${port}|`;
  const suffix = `|${modal}`;
  for (const [key, value] of Object.entries(RATES)) {
    if (!key.startsWith(prefix) || !key.endsWith(suffix)) continue;
    const known = key.slice(prefix.length, key.length - suffix.length);
    if (known.includes(dest) || dest.includes(known)) return priced(value);
  }
  return null;
}
